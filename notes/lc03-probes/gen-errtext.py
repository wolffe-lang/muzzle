#!/usr/bin/env python3
"""Writes src/errtext.S from glibc's strerror text as the differential
observed it (notes/lc03-evidence/expected/errno_strerror.out, lines
`strerror(N)=[text] errno=4242` for N = -2..140). glibc is a black box
here: its output, never its source. A number whose text is
"Unknown error N" gets no entry; strerror formats those itself.
    python3 -I notes/lc03-probes/gen-errtext.py EXPECTED.out > src/errtext.S
"""
import re, sys

texts = {}
for line in open(sys.argv[1], encoding="ascii"):
    m = re.fullmatch(r"strerror\((-?\d+)\)=\[(.*)\] errno=4242\n", line)
    if m:
        texts[int(m[1])] = m[2]
n = 134
out = []
w = out.append
w("/* muzzle: strerror's texts (lc03), the C locale's, one per errno Linux")
w(" * defines (0 to 133). Generated by notes/lc03-probes/gen-errtext.py from")
w(" * the text glibc's strerror answered in the differential")
w(" * (notes/lc03-evidence/expected/errno_strerror.out): the contract asks")
w(" * for glibc's text, observed as a black box. A number with no text has")
w(" * a null entry, and strerror formats \"Unknown error N\" for it.")
w(" * Assembly because a str literal's bytes cannot reach C as a char *")
w(" * yet (wolf-lang#604). Data only: wolf reads __muzzle_errtext through")
w(" * `extern \"c\" let`. */")
w("")
w("\t.section .data.rel.ro,\"aw\"")
w("\t.balign\t8")
w("\t.globl\t__muzzle_errtext")
w("\t.type\t__muzzle_errtext,@object")
w(f"\t.size\t__muzzle_errtext, {n * 8}")
w("__muzzle_errtext:")
kept = 0
for e in range(n):
    t = texts[e]
    if t == f"Unknown error {e}":
        w(f"\t.quad\t0\t\t/* {e} */")
    else:
        w(f"\t.quad\t.Le{e}")
        kept += 1
w("")
w("\t.section .rodata.str1.1,\"aMS\",@progbits,1")
for e in range(n):
    t = texts[e]
    if t != f"Unknown error {e}":
        assert all(32 <= ord(c) < 127 and c not in '"\\' for c in t), t
        w(f".Le{e}:\t.asciz\t\"{t}\"")
w("")
w("\t.section .note.GNU-stack,\"\",@progbits")
print("\n".join(out))
print(f"gen-errtext: {kept} texts, {n - kept} unknown", file=sys.stderr)
